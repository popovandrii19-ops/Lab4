// Завдання 197
void Task197() {
	printf("\n197. Задано послідовність чисел 1, 1/2, 1/3, 1/4, ... . Визначити, величину перших двох рядом елементів, що стоять, різниця яких менше 10^(–6). \n\n");
	float gap = 1.0f;
	int n = 1;
	while (gap >= 0.000001f) {
		gap = fabsf(1.0f / n - 1.0f / (n + 1));
		if (gap < 0.000001f) {
			break;
		}
		n++;
	}
	printf("Два елементи які дають різницю менше 10^(-6): 1/%d і 1/%d \n", n , n + 1);
}

