// Завдання 122
void Task122() {
	printf("\n122. Скласти програму, яка знаходить найбільше значення відношення тризначного числа до суми цифр.\n\n");
	float max_ratio = 0.0f;
	int max_number = 0;

	for (int i = 100; i <= 999; i++) {
		int sum_of_digits = (i / 100) + ((i / 10) % 10) + (i % 10);
		if (sum_of_digits != 0) {
			float ratio = (float)i / (float)sum_of_digits;
			if (ratio > max_ratio) {
				max_ratio = ratio;
				max_number = i;
			}
		}
	}
	printf("Найбільше значення відношення: %.2f\n", max_ratio);
	printf("Відповідне тризначне число: %d\n", max_number);
}

// Завдання 59
void Task59() {
	printf("\n59. Обчислити суму 1 - 2/3 * x + 3/4 * x^2 - 4/5 * x^3 + ... + 11/12 * x^10. якщо x = 2.\n");
	
	float sum = 1.0f;
	for (int n = 2; n <= 11; n++) {
		if (n % 2 == 0) {
			sum -= (float)n / (float)(n + 1) * powf(2.0f, n - 1);
		}
		else {
			sum += (float)n / (float)(n + 1) * powf(2.0f, n - 1);
		}
	}
	printf("Сума дорівнює: %.2f\n\n", sum);
}

